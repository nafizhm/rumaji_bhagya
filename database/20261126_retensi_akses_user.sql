CREATE TABLE IF NOT EXISTS mretensi_akses_user (
  userid VARCHAR(10) NOT NULL,
  c TINYINT(1) NOT NULL DEFAULT 0,
  r TINYINT(1) NOT NULL DEFAULT 0,
  u TINYINT(1) NOT NULL DEFAULT 0,
  d TINYINT(1) NOT NULL DEFAULT 0,
