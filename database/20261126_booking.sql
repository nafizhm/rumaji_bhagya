CREATE TABLE IF NOT EXISTS tbooking (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 no_registrasi VARCHAR(40) NOT NULL,
 request_key CHAR(32) NOT NULL,
 tanggal DATE NOT NULL,
 nama_lengkap VARCHAR(150) NOT NULL,
 nik CHAR(16) NOT NULL,
 no_telp VARCHAR(30) NOT NULL,
 projid INT NOT NULL,
 blok VARCHAR(3) NOT NULL,
 no VARCHAR(4) NOT NULL,
 nama_proyek VARCHAR(150) NOT NULL,
 marketing VARCHAR(100) NOT NULL,
 jenis_perumahan VARCHAR(30) NOT NULL,
 jenis_pembelian VARCHAR(30) NOT NULL,
 total_harga DECIMAL(18,0) NOT NULL,
 booking_fee DECIMAL(18,0) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Baru',
 data_pemohon LONGTEXT NOT NULL,
 berkas LONGTEXT NOT NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY uq_booking_registration (no_registrasi),
 UNIQUE KEY uq_booking_request (request_key),
 UNIQUE KEY uq_booking_unit (projid,blok,no),
 KEY idx_booking_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
